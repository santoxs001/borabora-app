function build(seed: Seed): Profile {
  const activeMins = seed.activeMinsAgo ?? 60;
  const joinedDays = seed.joinedDaysAgo ?? 100;
  const isNew = joinedDays <= 14;
  return {
    id: seed.id,
    name: seed.name,
    age: seed.age,
    city: seed.city,
    country: seed.country,
    bio: seed.bio,
    pronouns: seed.pronouns,
    genderIdentity: 'man',
    lookingFor: seed.lookingFor ?? ['see_what_happens'],
    interests: seed.interests,
    photos: photos(seed.id, seed.photoCount ?? 4),
    details: seed.details ?? {},
    icebreakers: (seed.icebreakers ?? []).map(([promptId, prompt, answer]) => ({
      promptId,
      prompt,
      answer,
    })),
    verified: seed.verified ?? false,
    isPlus: seed.isPlus ?? false,
    activeVibe: seed.vibe
      ? {
          key: seed.vibe,
          duration: '3h',
          startedAt: minutes(45),
          expiresAt: new Date(Date.now() + 135 * 60_000).toISOString(),
        }
      : null,
    distanceM: seed.distanceM,
    state: seed.state ?? (isNew ? 'new_here' : 'recently_active'),
    lastActiveAt: minutes(activeMins),
    joinedAt: days(joinedDays),
  };
}

export const MOCK_PROFILES: Profile[] = SEEDS.map(build);

export function isNewHere(p: Profile): boolean {
  return Date.now() - new Date(p.joinedAt).getTime() < 14 * 86_400_000;
}
