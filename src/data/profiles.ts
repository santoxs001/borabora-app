/* ────────────────────────────────────────────────────────────────
   Fixture profiles for the prototype.

   Photos are intentionally *generated* rather than fetched: the app
   ships no third-party imagery of real people, works offline, and the
   placeholder renderer doubles as the loading state for real photos.
   ──────────────────────────────────────────────────────────────── */

const minutes = (n: number): ISODate => new Date(Date.now() - n * 60_000).toISOString();
const days = (n: number): ISODate => new Date(Date.now() - n * 86_400_000).toISOString();

function photos(seedBase: string, count: number): Photo[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `${seedBase}-p${i}`,
    url: null,
    seed: `${seedBase}-${i}`,
    position: i,
    isPrimary: i === 0,
    moderation: 'approved' as const,
  }));
}

